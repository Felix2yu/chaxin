export function icon(name, cls = '') {
  const inner = ICONS[name] || '';
  // GitHub 图标为实心 logo，其余均为描边线性图标
  if (name === 'github') {
    return `<svg class="${cls}" viewBox="0 0 24 24" fill="currentColor" stroke="none">${inner}</svg>`;
  }
  return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
}

// ---- Toast ----
let toastRoot = null;

export function initToast() {
  toastRoot = document.getElementById('toast-root');
}

export function toast(message, type = 'info') {
  if (!toastRoot) return;
  const el = document.createElement('div');
  el.className = `toast toast--${type}`;
  el.innerHTML = `${icon(type === 'error' ? 'alert' : type === 'success' ? 'check' : 'info')}<span></span>`;
  el.querySelector('span').textContent = message;
  toastRoot.appendChild(el);
  setTimeout(() => {
    el.style.transition = 'opacity .25s, transform .25s';
    el.style.opacity = '0';
    el.style.transform = 'translateY(8px)';
    setTimeout(() => el.remove(), 250);
  }, 3200);
}

// 简单防抖
export function debounce(fn, wait = 300) {
  let t = null;
  return (...args) => {
    clearTimeout(t);
    t = setTimeout(() => fn(...args), wait);
  };
}

// 时间格式化（短）
export function fmtShort(t) {
  if (!t) return '-';
  const d = new Date(t);
  if (isNaN(d.getTime())) return '-';
  const pad = (n) => String(n).padStart(2, '0');
  return `${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

// 时间格式化（完整）
export function fmtFull(t) {
  if (!t) return '-';
  const d = new Date(t);
  if (isNaN(d.getTime())) return '-';
  return d.toLocaleString('zh-CN');
}
